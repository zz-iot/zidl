#!/usr/bin/env python3
"""Independent binary64-to-packed-decimal known answers, including 31 digits."""
import math
import struct
from pathlib import Path

def bits(value):
    return '0x' + struct.pack('>d', value).hex()

def factor(scale):
    result = 1.0
    for _ in range(scale): result *= 10.0
    return result

def wire(digits, integer, negative):
    return ('0' if digits % 2 == 0 else '') + str(integer).zfill(digits) + ('d' if negative else 'c')

inputs = [(5,2,123.45),(5,2,-123.45),(4,2,12.34),(1,0,7.0),
          (3,1,0.0),(3,1,-0.0),(1,0,0.5),(1,0,-0.5),(1,0,-0.01),
          (5,2,99999.0),(5,2,-math.inf),(5,2,math.inf)]
for digits in [18,19,20,30,31]:
    for scale in [0,digits]:
        for value in [1.0,-1.0,1e30,-1e30,1.2345678901234567e20]:
            inputs.append((digits,scale,value))
inputs += [(31,0,math.nextafter(1e31,0)), (31,0,1e31), (31,31,5e-324)]
rows=[]
for digits,scale,value in inputs:
    rounded = abs(value) * factor(scale) + 0.5
    integer = 10**digits-1 if rounded >= float(10**digits) else int(rounded)
    negative = value < 0 and integer != 0
    decoded = float(integer) / factor(scale)
    if negative: decoded = -decoded
    rows.append(f'    .{{ .digits = {digits}, .scale = {scale}, .value = @bitCast(@as(u64, {bits(value)})), .hex = "{wire(digits,integer,negative)}", .decoded = @bitCast(@as(u64, {bits(decoded)})) }},')
reads=[]
for digits,scale,integer,negative in [
    (31,0,1234567890123456789012345678901,False),
    (31,17,1234567890123456789012345678901,True),
    (30,29,987654321098765432109876543210,False),
    (31,31,10**31-1,False),(31,0,0,True),
    (20,0,18446744073709551615,False),(20,0,18446744073709551616,False),
    (31,0,2**100+2**47,False),(31,0,2**100+3*2**47,False),
]:
    value=float(integer)/factor(scale)
    if negative:value=-value
    reads.append(f'    .{{ .digits = {digits}, .scale = {scale}, .hex = "{wire(digits,integer,negative)}", .decoded = @bitCast(@as(u64, {bits(value)})) }},')
source='''// Generated by zidl-cdr/test/make_fixed_vectors.py; no runtime codec is used.
pub const Case = struct { digits: u8, scale: u8, value: f64 = 0, hex: []const u8, decoded: f64 };
pub const cases = [_]Case{\n'''+ '\n'.join(rows)+'\n};\npub const read_cases = [_]Case{\n'+'\n'.join(reads)+'\n};\n'
Path(__file__).resolve().parents[1].joinpath('src/fixed_test_cases.zig').write_text(source)
