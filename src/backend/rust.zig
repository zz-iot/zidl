//! Experimental owned Rust mapping for final fixed-shape values.
const std = @import("std");
const ast = @import("../ast.zig");
const ir = @import("../ir/root.zig");
const interface = @import("interface.zig");
const cdr_skip = @import("cdr_skip.zig");

pub const RustBackend = struct {
    alloc: std.mem.Allocator,

    pub fn create(alloc: std.mem.Allocator) !*RustBackend {
        const self = try alloc.create(RustBackend);
        self.* = .{ .alloc = alloc };
        return self;
    }
    pub fn backend(self: *RustBackend) interface.Backend {
        return .{ .ctx = self, .vtable = &vtable };
    }
    const vtable: interface.Backend.Vtable = .{
        .language_id = "rust",
        .generate = generate,
        .deinit = deinit,
    };
    fn deinit(ctx: *anyopaque) void {
        const self: *RustBackend = @ptrCast(@alignCast(ctx));
        self.alloc.destroy(self);
    }
    fn generate(ctx: *anyopaque, spec: *const ir.Spec, opts: interface.Options) !void {
        const self: *RustBackend = @ptrCast(@alignCast(ctx));
        if (opts.split_files or opts.generate_interfaces or opts.generate_zzdds_wrappers or
            opts.type_prefix.len != 0 or opts.profile != .full or opts.pl_cdr)
            return unsupported("generation option", opts.input_stem);
        if (spec.imports.len != 0 or spec.warnings.len != 0)
            return unsupported("imports or unrepresented declarations", opts.input_stem);
        var validator = Validator{ .alloc = self.alloc, .opts = opts };
        defer validator.seen.deinit(self.alloc);
        try validator.items(spec.items);
        var emitter = Emitter{ .alloc = self.alloc, .codecs = !opts.no_typesupport };
        defer emitter.out.deinit(self.alloc);
        try emitter.print("// Generated by zidl; experimental final Rust mapping.\n", .{});
        try emitter.items(spec.items, 0);
        const filename = try std.fmt.allocPrint(self.alloc, "{s}.rs", .{opts.input_stem});
        defer self.alloc.free(filename);
        const path = try std.fs.path.join(self.alloc, &.{ opts.output_dir, filename });
        defer self.alloc.free(path);
        const io = std.Io.Threaded.global_single_threaded.io();
        const file = try std.Io.Dir.cwd().createFile(io, path, .{});
        defer file.close(io);
        var buffer: [4096]u8 = undefined;
        var writer: std.Io.File.Writer = .init(file, io, &buffer);
        try writer.interface.writeAll(emitter.out.items);
        try writer.interface.flush();
    }
};

fn unsupported(feature: []const u8, name: []const u8) error{UnsupportedRustMapping} {
    std.log.err("Rust backend does not support {s}: {s}", .{ feature, name });
    return error.UnsupportedRustMapping;
}

fn identifier(name: []const u8) !void {
    for ([_][]const u8{ "self", "Self", "super", "crate", "_" }) |reserved| {
        if (std.mem.eql(u8, name, reserved)) return unsupported("reserved identifier", name);
    }
}

fn primitive(base: ast.BaseTypeSpec) ?[]const u8 {
    return switch (base) {
        .boolean => "bool",
        .char, .octet, .uint8 => "u8",
        .int8 => "i8",
        .short, .int16 => "i16",
        .unsigned_short, .uint16 => "u16",
        .long, .int32 => "i32",
        .unsigned_long, .uint32 => "u32",
        .long_long, .int64 => "i64",
        .unsigned_long_long, .uint64 => "u64",
        .float => "f32",
        .double => "f64",
        else => null,
    };
}

const Validator = struct {
    alloc: std.mem.Allocator,
    opts: interface.Options,
    seen: std.AutoHashMapUnmanaged(usize, enum { active, done }) = .empty,

    fn items(self: *Validator, list: []const ir.ModuleItem) anyerror!void {
        for (list) |item| switch (item) {
            .module => |m| {
                try identifier(m.name);
                if (m.is_imported) return unsupported("imported module", m.name);
                try self.items(m.items);
            },
            .type_decl => |td| try self.named(td),
            .const_ => |c| return unsupported("constant declaration", c.name),
        };
    }
    fn named(self: *Validator, td: ir.TypeDecl) anyerror!void {
        const name = ir.typeDeclQualifiedName(td);
        try identifier(ir.typeDeclName(td));
        const address = switch (td) {
            inline else => |p| @intFromPtr(p),
        };
        if (self.seen.get(address)) |state| {
            if (state == .active) return unsupported("recursive value", name);
            return;
        }
        try self.seen.put(self.alloc, address, .active);
        switch (td) {
            .struct_ => |s| {
                if (s.base != null) return unsupported("struct inheritance", name);
                if (s.annotations.extensibility != .final or self.opts.default_extensibility != .final)
                    return unsupported("non-final extensibility", name);
                for (s.members) |m| {
                    try identifier(m.name);
                    if (m.annotations.is_optional or m.annotations.is_key or m.annotations.default_value != null or m.annotations.is_pl_repeated)
                        return unsupported("optional, key or default member", m.name);
                    try self.array(m.type_ref, m.dimensions, m.name);
                }
            },
            .enum_ => |e| {
                if (e.annotations.bit_bound != null and e.annotations.bit_bound.? != 32)
                    return unsupported("enum bit_bound other than 32", name);
                for (e.enumerators) |value| {
                    try identifier(value.name);
                    if (value.value > std.math.maxInt(u32)) return unsupported("enum value beyond u32", name);
                    if (std.mem.eql(u8, value.name, "encode") or std.mem.eql(u8, value.name, "decode"))
                        return unsupported("enum codec name collision", value.name);
                }
            },
            .typedef => |t| try self.array(t.type_ref, t.dimensions, t.name),
            else => return unsupported("declaration kind", name),
        }
        try self.seen.put(self.alloc, address, .done);
    }
    fn array(self: *Validator, tr: ir.TypeRef, dims: []const u64, name: []const u8) !void {
        if (dims.len != 0 and !cdr_skip.isPrimitiveElement(cdr_skip.arrayInnermost(tr)))
            return unsupported("non-primitive array requiring XCDR2 collection framing", name);
        try self.ref(tr);
    }
    fn ref(self: *Validator, tr: ir.TypeRef) anyerror!void {
        switch (tr) {
            .base => |b| if (primitive(b) == null) {
                return unsupported("primitive", @tagName(b));
            },
            .named => |td| try self.named(td),
            else => return unsupported("variable-length or fixed-decimal value", @tagName(tr)),
        }
    }
};

const Emitter = struct {
    alloc: std.mem.Allocator,
    codecs: bool,
    out: std.ArrayList(u8) = .empty,

    fn print(self: *Emitter, comptime format: []const u8, args: anytype) !void {
        const text = try std.fmt.allocPrint(self.alloc, format, args);
        defer self.alloc.free(text);
        try self.out.appendSlice(self.alloc, text);
    }
    fn path(self: *Emitter, td: ir.TypeDecl, depth: usize) !void {
        if (depth == 0) try self.print("self::", .{});
        for (0..depth) |_| try self.print("super::", .{});
        var parts = std.mem.tokenizeSequence(u8, ir.typeDeclQualifiedName(td), "::");
        var first = true;
        while (parts.next()) |part| {
            if (!first) try self.print("::", .{});
            try self.print("r#{s}", .{part});
            first = false;
        }
    }
    fn typ(self: *Emitter, tr: ir.TypeRef, dims: []const u64, depth: usize) anyerror!void {
        if (dims.len != 0) {
            try self.print("[", .{});
            try self.typ(tr, dims[1..], depth);
            try self.print("; {d}]", .{dims[0]});
            return;
        }
        switch (tr) {
            .base => |b| try self.print("{s}", .{primitive(b).?}),
            .named => |td| try self.path(td, depth),
            else => unreachable,
        }
    }
    fn items(self: *Emitter, list: []const ir.ModuleItem, depth: usize) anyerror!void {
        for (list) |item| switch (item) {
            .module => |m| {
                try self.print("#[allow(non_snake_case)]\npub mod r#{s} {{\n", .{m.name});
                try self.items(m.items, depth + 1);
                try self.print("}}\n", .{});
            },
            .type_decl => |td| switch (td) {
                .struct_ => |s| try self.structure(s, depth),
                .enum_ => |e| try self.enumeration(e),
                .typedef => |t| {
                    try self.print("#[allow(non_camel_case_types)]\npub type r#{s} = ", .{t.name});
                    try self.typ(t.type_ref, t.dimensions, depth);
                    try self.print(";\n", .{});
                },
                else => unreachable,
            },
            else => unreachable,
        };
    }
    fn structure(self: *Emitter, s: *const ir.Struct, depth: usize) !void {
        try self.print("#[allow(non_camel_case_types, non_snake_case)]\n#[derive(Debug, Clone, PartialEq)]\npub struct r#{s} {{\n", .{s.name});
        for (s.members) |m| {
            try self.print("pub r#{s}: ", .{m.name});
            try self.typ(m.type_ref, m.dimensions, depth);
            try self.print(",\n", .{});
        }
        try self.print("}}\n", .{});
        if (!self.codecs) return;
        try self.print("impl r#{s} {{\npub fn encode<W: ::zidl_cdr_rust::Write>(&self, writer: &mut W) -> Result<(), ::zidl_cdr_rust::Error> {{\n", .{s.name});
        for (s.members) |m| {
            const expr = try std.fmt.allocPrint(self.alloc, "&self.r#{s}", .{m.name});
            defer self.alloc.free(expr);
            try self.write(m.type_ref, m.dimensions, expr, 0);
        }
        try self.print("Ok(())\n}}\npub fn decode(reader: &mut ::zidl_cdr_rust::Reader<'_>) -> Result<Self, ::zidl_cdr_rust::Error> {{\nOk(Self {{\n", .{});
        for (s.members) |m| {
            try self.print("r#{s}: ", .{m.name});
            try self.read(m.type_ref, m.dimensions, depth);
            try self.print("?,\n", .{});
        }
        try self.print("}})\n}}\n}}\n", .{});
    }
    fn enumeration(self: *Emitter, e: *const ir.Enum) !void {
        try self.print("#[allow(non_camel_case_types)]\n#[repr(transparent)]\n#[derive(Debug, Clone, Copy, PartialEq, Eq)]\npub struct r#{s}(pub u32);\n#[allow(non_upper_case_globals)]\nimpl r#{s} {{\n", .{ e.name, e.name });
        for (e.enumerators) |value| try self.print("pub const r#{s}: Self = Self({d});\n", .{ value.name, value.value });
        if (self.codecs) try self.print("pub fn encode<W: ::zidl_cdr_rust::Write>(&self, writer: &mut W) -> Result<(), ::zidl_cdr_rust::Error> {{ writer.write_u32(self.0) }}\npub fn decode(reader: &mut ::zidl_cdr_rust::Reader<'_>) -> Result<Self, ::zidl_cdr_rust::Error> {{ Ok(Self(reader.read_u32()?)) }}\n", .{});
        try self.print("}}\n", .{});
    }
    fn write(self: *Emitter, tr: ir.TypeRef, dims: []const u64, expr: []const u8, level: usize) anyerror!void {
        if (dims.len != 0) {
            const item = try std.fmt.allocPrint(self.alloc, "__item{d}", .{level});
            defer self.alloc.free(item);
            try self.print("for {s} in {s} {{\n", .{ item, expr });
            try self.write(tr, dims[1..], item, level + 1);
            try self.print("}}\n", .{});
            return;
        }
        switch (tr) {
            .base => |b| try self.print("writer.write_{s}(*({s}))?;\n", .{ primitive(b).?, expr }),
            .named => |td| switch (td) {
                .typedef => |t| try self.write(t.type_ref, t.dimensions, expr, level),
                else => try self.print("({s}).encode(writer)?;\n", .{expr}),
            },
            else => unreachable,
        }
    }
    fn read(self: *Emitter, tr: ir.TypeRef, dims: []const u64, depth: usize) anyerror!void {
        if (dims.len != 0) {
            try self.print("::zidl_cdr_rust::read_array(reader, |reader| ", .{});
            try self.read(tr, dims[1..], depth);
            try self.print(")", .{});
            return;
        }
        switch (tr) {
            .base => |b| try self.print("reader.read_{s}()", .{primitive(b).?}),
            .named => |td| switch (td) {
                .typedef => |t| try self.read(t.type_ref, t.dimensions, depth),
                else => {
                    try self.path(td, depth);
                    try self.print("::decode(reader)", .{});
                },
            },
            else => unreachable,
        }
    }
};
